"""Read-only exact-SHA GitHub ruleset/check evidence and non-draft admission probe.

This extension to CODEX #1042 never writes GitHub settings or merges PRs.
Inputs are owner-captured API readbacks, not claims generated by the test.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

SCHEMA = "code-purple.protection-evidence.v2"
PASS = {"success"}
BAD = {"failure", "cancelled", "timed_out", "action_required", "startup_failure"}
BLOCKED = {"blocked", "dirty", "behind"}  # mergeable_state=blocked is authoritative only with real enforced policy


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _branches_match(branches, target):
    if branches is None:
        return True
    if not isinstance(branches, list):
        return False
    return target in branches or "**" in branches


def assess(data: dict) -> dict:
    if data.get("schema") != SCHEMA:
        raise ValueError("schema mismatch")
    repo = data.get("repository")
    head = data.get("pr_head_sha")
    if not isinstance(repo, str) or "/" not in repo:
        raise ValueError("repository missing")
    if not isinstance(head, str) or len(head) != 40 or any(c not in "0123456789abcdef" for c in head):
        raise ValueError("exact PR head missing")
    target = data.get("default_branch")
    if not isinstance(target, str) or not target:
        raise ValueError("default branch missing")
    rulesets = data.get("rulesets")
    if not isinstance(rulesets, list):
        rulesets = []
    matched = [r for r in rulesets if r.get("enforcement") == "active"
               and r.get("target") == "branch"
               and ("~DEFAULT_BRANCH" in (r.get("conditions", {}).get("ref_name", {}).get("include", []))
                    or target in r.get("conditions", {}).get("ref_name", {}).get("include", []))]
    required = {}
    for r in matched:
        for rule in r.get("rules", []):
            if rule.get("type") != "required_status_checks":
                continue
            params = rule.get("parameters", {})
            for item in params.get("required_status_checks", []):
                name = item.get("context")
                if not isinstance(name, str) or not name:
                    raise ValueError("empty mandatory check context")
                source = item.get("integration_id")
                if name in required and required[name] != source:
                    raise ValueError("conflicting check source identity")
                required[name] = source
    check_runs = data.get("check_runs")
    if not isinstance(check_runs, list):
        check_runs = []
    workflows = data.get("workflows")
    if not isinstance(workflows, list):
        workflows = []
    lines = []
    for name, source in sorted(required.items()):
        actual = [x for x in check_runs if x.get("name") == name and x.get("head_sha") == head]
        if source is not None:
            actual = [x for x in actual if x.get("app", {}).get("id") == source]
        complete = [x for x in actual if x.get("status") == "completed"]
        proven = [x for x in complete if x.get("conclusion") in PASS]
        nonpassing = [x for x in complete if x.get("conclusion") in BAD]
        skipped = [x for x in complete if x.get("conclusion") in ("skipped", "neutral")]
        producers = [w for w in workflows if name in w.get("job_contexts", [])]
        applicable = [w for w in producers
                      if "pull_request" in w.get("events", [])
                      and _branches_match(w.get("pr_target_branches"), target)
                      and not w.get("path_filters")
                      and not w.get("job_conditional")]
        if not producers:
            state = "UNKNOWN_PRODUCER"
        elif not applicable:
            state = "CONDITIONAL_OR_NONUNIVERSAL_PRODUCER"
        elif nonpassing:
            state = "FAILED_CHECK"
        elif skipped:
            state = "SKIPPED_NOT_PROVEN"
        elif proven:
            state = "PASS"
        else:
            state = "MISSING_OR_PENDING"
        lines.append({"context": name, "expected_app_id": source, "state": state,
                      "matching_exact_head_count": len(actual),
                      "matching_terminal_success_count": len(proven),
                      "applicable_unconditional_producer_count": len(applicable)})
    pr = data.get("pr") or {}
    nondraft = pr.get("draft") is False
    pr_sha_matches = pr.get("head_sha") == head
    github_merge_state = pr.get("mergeable_state")
    unsatisfied = [x["context"] for x in lines if x["state"] != "PASS"]
    effective = data.get("branch_protected") is True and bool(matched) and bool(required)
    # 'blocked' is not sufficient proof of a status-check gate: reviewer or other rules may also block.
    negative_proven = (effective and nondraft and pr_sha_matches and bool(unsatisfied)
                       and pr.get("mergeable") is False
                       and github_merge_state in BLOCKED
                       and pr.get("blocking_reason") == "required_status_checks"
                       and pr.get("blocking_reason_source") == "LIVE_GITHUB_READBACK")
    return {
        "schema": SCHEMA, "source_digest": digest(data), "repo": repo,
        "exact_head": head, "required_contexts": lines, "effective_required_rule": effective,
        "mandatory_checks_proven": bool(lines) and all(x["state"] == "PASS" for x in lines),
        "negative_probe": {
            "non_draft": nondraft, "exact_head": pr_sha_matches,
            "github_mergeable": pr.get("mergeable"), "github_mergeable_state": github_merge_state,
            "unsatisfied_contexts": unsatisfied,
            "blocked_by_check_proven": negative_proven,
            "disposition": "PASS" if negative_proven else "UNPROVEN",
        },
        "merge_admission": "HOLD", "authority_transfer": False, "mutation": False,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--snapshot", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = assess(json.loads(args.snapshot.read_text()))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"negative_probe": result["negative_probe"]["disposition"],
                      "required_contexts": len(result["required_contexts"])}))


if __name__ == "__main__":
    main()
