"""Contract tests for the generated federation wave register (CANDIDATE)."""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REG = ROOT / "federation" / "waves" / "WAVE_REGISTER.yaml"
NS = ROOT / "federation" / "waves" / "WAVE_NAMESPACES.yaml"


def load(p: Path):
    return yaml.safe_load(p.read_text(encoding="utf-8"))


def test_register_is_ascii_and_marked_generated():
    raw = REG.read_bytes()
    raw.decode("ascii")
    assert raw.startswith(b"# GENERATED by scripts/build_wave_register.py")


def test_keys_unique_and_namespaced():
    reg, ns = load(REG), load(NS)
    keys = [e["key"] for e in reg["waves"]]
    assert len(keys) == len(set(keys))
    allowed = {n["key"] for n in ns["namespaces"]}
    statuses = set(ns["status_enum"])
    for e in reg["waves"]:
        assert e["key"] == "%s:%s" % (e["namespace"], e["id"])
        assert e["namespace"] in allowed
        assert e["status"] in statuses
        assert e["confidence"] in {"exact", "inferred"}
        assert e["repos"], e["key"]
    assert reg["stats"]["entries"] == len(reg["waves"]) > 0


def test_index_only_no_authority_transfer():
    reg = load(REG)
    assert reg["authority"] == "index_only"
    assert reg["authority_transfer"] is False


def test_private_sources_leak_no_file_names():
    reg = load(REG)
    private = {r for r, m in reg["sources"].items() if m["visibility"] == "private"}
    for e in reg["waves"]:
        for repo, v in e["repos"].items():
            if repo in private:
                assert set(v) <= {"paths", "anchor"}, (e["key"], repo)


def test_sources_are_sha_anchored():
    for repo, m in load(REG)["sources"].items():
        assert re.fullmatch(r"[0-9a-f]{40}", m["head"]), repo


def test_codex_evidence_paths_exist():
    reg = load(REG)
    for e in reg["waves"]:
        for p in e["repos"].get("GBOGEB/CODEX", {}).get("evidence", []):
            assert (ROOT / p).exists(), p
